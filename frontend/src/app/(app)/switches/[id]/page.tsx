"use client";

import { ArrowLeft, Pencil, RefreshCw, Trash2 } from "lucide-react";
import Link from "next/link";
import { useParams, useRouter, useSearchParams } from "next/navigation";
import { Suspense, useState } from "react";
import { ChangeDialog, type ChangeRequest } from "@/components/ChangeDialog";
import { PortsTab } from "@/components/switch/PortsTab";
import { ConfigTab, DevicesTab, EventsTab, MonitoringTab, NeighborsTab, OverviewTab, PoeTab, SecurityTab, VlansTab } from "@/components/switch/Tabs";
import { SwitchForm } from "@/components/SwitchForm";
import { Button, ConfirmDialog, Loadable, Modal, Notice, SimBadge, StaleBadge, StatusBadge, Tabs, useToast } from "@/components/ui";
import { api, errorMessage } from "@/lib/api";
import { useAuth } from "@/lib/auth";
import { PROTOCOL_LABEL, fmtDate, relTime } from "@/lib/format";
import { useApi } from "@/lib/hooks";
import type { SwitchDetail } from "@/lib/types";

const TABS = ["overview", "ports", "vlans", "poe", "devices", "neighbors", "monitoring", "configuration", "security", "events"] as const;
type Tab = (typeof TABS)[number];

function SwitchDetailPage() {
  const { id } = useParams<{ id: string }>();
  const params = useSearchParams();
  const router = useRouter();
  const toast = useToast();
  const { can } = useAuth();
  const initialTab = (TABS as readonly string[]).includes(params.get("tab") || "") ? (params.get("tab") as Tab) : "overview";
  const [tab, setTabState] = useState<Tab>(initialTab);
  const [change, setChange] = useState<ChangeRequest | null>(null);
  const [editing, setEditing] = useState(false);
  const [deleting, setDeleting] = useState(false);
  const [polling, setPolling] = useState(false);
  const { data, error, mutate } = useApi<SwitchDetail>(`/switches/${id}`, undefined, { live: true });

  const setTab = (t: Tab) => {
    setTabState(t);
    router.replace(`/switches/${id}?tab=${t}`, { scroll: false });
  };

  const pollNow = async () => {
    setPolling(true);
    try {
      for (const c of ["availability", "inventory", "health", "counters", "poe", "mac", "lldp"]) {
        await api(`/switches/${id}/poll`, { method: "POST", query: { category: c } });
      }
      toast("ok", "Switch polled");
      mutate();
    } catch (e) {
      toast("bad", errorMessage(e));
    } finally {
      setPolling(false);
    }
  };

  return (
    <div>
      <Link href="/switches" className="mb-2 inline-flex items-center gap-1 text-sm text-muted hover:text-fg">
        <ArrowLeft className="h-4 w-4" /> Switches
      </Link>
      <Loadable data={data} error={error} retry={() => mutate()}>
        {(sw) => (
          <>
            <div className="mb-4 flex flex-wrap items-start justify-between gap-3">
              <div>
                <h1 className="flex flex-wrap items-center gap-2 text-xl font-semibold">
                  {sw.hostname} <StatusBadge status={sw.status} /> <SimBadge show={sw.is_simulated} />
                  <StaleBadge at={sw.last_success_at} stale={sw.poll_stale} />
                </h1>
                <p className="mt-0.5 text-sm text-muted">
                  <span className="font-mono">{sw.mgmt_ip}</span> · {sw.product_number || "unknown model"} · {sw.firmware || "firmware unknown"} · last poll {relTime(sw.last_poll_at)}
                </p>
                {sw.status_reason && <p className="mt-1 text-sm text-warn">{sw.status_reason}</p>}
              </div>
              <div className="flex flex-wrap gap-2">
                {can("switch.manage") && (
                  <Button onClick={pollNow} loading={polling}>
                    <RefreshCw className="h-4 w-4" /> Poll now
                  </Button>
                )}
                {can("switch.manage") && (
                  <Button onClick={() => setEditing(true)}>
                    <Pencil className="h-4 w-4" /> Edit
                  </Button>
                )}
                {can("switch.delete") && (
                  <Button variant="danger" onClick={() => setDeleting(true)}>
                    <Trash2 className="h-4 w-4" /> Remove
                  </Button>
                )}
              </div>
            </div>
            {sw.is_simulated && (
              <div className="mb-4">
                <Notice tone="sim">This switch is generated by the built-in simulator. Its data and any changes made to it are not real.</Notice>
              </div>
            )}
            {Object.entries(sw.credential_problems || {}).map(([proto, pr]) => (
              <div key={proto} className="mb-4">
                <Notice tone="bad">
                  <strong>{PROTOCOL_LABEL[proto] || proto} credential rejected</strong> by this switch since {fmtDate(pr!.since)}: {pr!.message}.{" "}
                  {can("credential.manage") ? (
                    <Link href="/admin/credentials" className="underline">
                      Fix it in Device credentials
                    </Link>
                  ) : (
                    "Ask a Super Admin to fix it in Device credentials."
                  )}
                </Notice>
              </div>
            ))}
            {!sw.monitoring_enabled && (
              <div className="mb-4">
                <Notice tone="warn">Monitoring is disabled for this switch. Data shown may be out of date.</Notice>
              </div>
            )}
            <Tabs<Tab>
              value={tab}
              onChange={setTab}
              tabs={[
                { id: "overview", label: "Overview" },
                { id: "ports", label: "Ports", hidden: !can("port.view") },
                { id: "vlans", label: "VLANs", hidden: !can("vlan.view") },
                { id: "poe", label: "PoE", hidden: !can("poe.view") },
                { id: "devices", label: "Devices", hidden: !can("device.view") },
                { id: "neighbors", label: "Neighbours", hidden: !can("topology.view") },
                { id: "monitoring", label: "Monitoring", hidden: !can("metrics.view") },
                { id: "configuration", label: "Configuration", hidden: !can("backup.view") },
                { id: "security", label: "Security", hidden: !can("switch.manage") && !can("netsec.manage") },
                { id: "events", label: "Events", hidden: !can("event.view") },
              ]}
            />
            {tab === "overview" && <OverviewTab sw={sw} />}
            {tab === "ports" && <PortsTab sw={sw} initialPort={params.get("port")} onChange={setChange} />}
            {tab === "vlans" && <VlansTab sw={sw} onChange={setChange} />}
            {tab === "poe" && <PoeTab sw={sw} onChange={setChange} />}
            {tab === "devices" && <DevicesTab sw={sw} />}
            {tab === "neighbors" && <NeighborsTab sw={sw} />}
            {tab === "monitoring" && <MonitoringTab sw={sw} />}
            {tab === "configuration" && <ConfigTab sw={sw} onChange={setChange} />}
            {tab === "security" && <SecurityTab sw={sw} onChange={setChange} reload={() => mutate()} />}
            {tab === "events" && <EventsTab sw={sw} />}

            <Modal open={editing} onClose={() => setEditing(false)} title={`Edit ${sw.hostname}`} wide>
              <SwitchForm
                initial={sw}
                onCancel={() => setEditing(false)}
                onSaved={() => {
                  setEditing(false);
                  toast("ok", "Switch updated");
                  mutate();
                }}
              />
            </Modal>
            <ConfirmDialog
              open={deleting}
              onClose={() => setDeleting(false)}
              danger
              title="Remove switch"
              typeToConfirm={sw.hostname}
              confirmLabel="Remove from inventory"
              message={
                <>
                  This removes <strong>{sw.hostname}</strong> and its collected data, credentials and configuration backups from the application. Nothing is changed on the switch
                  itself.
                </>
              }
              onConfirm={async () => {
                await api(`/switches/${sw.id}`, { method: "DELETE", body: { confirm_hostname: sw.hostname } });
                toast("ok", `${sw.hostname} removed`);
                router.push("/switches");
              }}
            />
          </>
        )}
      </Loadable>
      <ChangeDialog request={change} onClose={() => setChange(null)} />
    </div>
  );
}

export default function Page() {
  return (
    <Suspense>
      <SwitchDetailPage />
    </Suspense>
  );
}
